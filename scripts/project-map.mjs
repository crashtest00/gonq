#!/usr/bin/env node
// Builds the project map from the header comment at the top of every source file under apps/desktop/src/, packages/editor/src/, crates/gonq-core/src/ and
// apps/desktop/src-tauri/src/. Each file's header is the source of truth; PROJECT_MAP.md is generated (gitignored).
//
//   node scripts/project-map.mjs          writes PROJECT_MAP.md, grouped by directory
//   node scripts/project-map.mjs --json   prints [{ path, summary }] to stdout
//   node scripts/project-map.mjs --check  exits 1 listing every source file without a header
//
// A header is, ignoring leading blank lines: in .ts/.tsx a `/** ... */` block or a run of `//` lines;
// in .rs a run of `//!` lines. The map shows its first paragraph, collapsed to one line.
// Node 18+, no dependencies.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE_DIRS = ['apps/desktop/src', 'crates/gonq-core/src', 'apps/desktop/src-tauri/src', 'packages/editor/src'];
const SOURCE_FILE = /\.(tsx?|rs)$/;
const OUTPUT = 'PROJECT_MAP.md';

function walk(dir) {
  const out = [];
  if (!existsSync(join(ROOT, dir))) return out; // a configured root that does not exist (yet)
  for (const entry of readdirSync(join(ROOT, dir), { withFileTypes: true })) {
    const path = `${dir}/${entry.name}`;
    if (entry.isDirectory()) out.push(...walk(path));
    else if (SOURCE_FILE.test(entry.name)) out.push(path);
  }
  return out;
}

/** The header's comment text, one string per line with the comment syntax removed; null when there is none. */
function headerLines(path, text) {
  const lines = text.replace(/^﻿/, '').split(/\r?\n/);
  let i = 0;
  while (i < lines.length && lines[i].trim() === '') i++;
  const first = (lines[i] ?? '').trim();
  const out = [];
  if (path.endsWith('.rs')) {
    for (; i < lines.length && lines[i].trim().startsWith('//!'); i++) out.push(lines[i].trim().slice(3));
  } else if (first.startsWith('/**')) {
    for (; i < lines.length; i++) {
      const line = lines[i].trim();
      const end = line.indexOf('*/');
      const body = (end >= 0 ? line.slice(0, end) : line).replace(/^\/\*\*/, '').replace(/^\*/, '');
      out.push(body);
      if (end >= 0) break;
    }
  } else if (first.startsWith('//') && !first.startsWith('///')) {
    for (; i < lines.length && lines[i].trim().startsWith('//'); i++) out.push(lines[i].trim().slice(2));
  }
  return out.some((l) => l.trim() !== '') ? out : null;
}

/** First paragraph of the header, collapsed to one line. */
function summarize(lines) {
  const para = [];
  for (const line of lines) {
    if (line.trim() === '') {
      if (para.length) break;
      continue;
    }
    para.push(line.trim());
  }
  return para.join(' ').replace(/\s+/g, ' ').trim();
}

function collect() {
  return SOURCE_DIRS.flatMap(walk)
    .sort((a, b) => a.localeCompare(b))
    .map((path) => {
      const lines = headerLines(path, readFileSync(join(ROOT, path), 'utf8'));
      return { path, summary: lines ? summarize(lines) : null };
    });
}

function render(entries) {
  const byDir = new Map();
  for (const e of entries) {
    const dir = e.path.slice(0, e.path.lastIndexOf('/') + 1);
    if (!byDir.has(dir)) byDir.set(dir, []);
    byDir.get(dir).push(e);
  }
  const out = [
    '# Gonq project map',
    '',
    'Generated by `npm run map` from the header comment at the top of each source file.',
    'Do not edit or commit it: change the header in the file instead.',
    '',
  ];
  for (const [dir, files] of byDir) {
    out.push(`## ${dir}`, '');
    for (const e of files) out.push(`- ${e.path} — ${e.summary ?? '(no header)'}`);
    out.push('');
  }
  return out.join('\n');
}

const args = new Set(process.argv.slice(2));
const entries = collect();
const missing = entries.filter((e) => e.summary === null).map((e) => e.path);

if (args.has('--check')) {
  if (missing.length) {
    console.error(`${missing.length} source file(s) without a header comment (see Conventions in CLAUDE.md):`);
    for (const p of missing) console.error(`  ${p}`);
    process.exit(1);
  }
  console.log(`project map: all ${entries.length} source files have a header comment.`);
} else if (args.has('--json')) {
  const json = entries.map(({ path, summary }) => ({ path, summary: summary ?? '' }));
  process.stdout.write(JSON.stringify(json, null, 2) + '\n');
} else {
  writeFileSync(join(ROOT, OUTPUT), render(entries));
  console.log(`wrote ${OUTPUT}: ${entries.length} files`);
  if (missing.length) console.error(`warning: ${missing.length} file(s) without a header; run npm run map:check`);
}
